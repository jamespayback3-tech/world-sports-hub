create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  summary text not null default '',
  category text not null default 'Other',
  source_name text not null default 'Unknown source',
  source_url text not null unique,
  published_at timestamptz,
  status text not null default 'published' check (status in ('published','draft')),
  created_at timestamptz not null default now()
);
create index if not exists articles_published_at_idx on public.articles (published_at desc);
create index if not exists articles_category_idx on public.articles (category);
alter table public.articles enable row level security;
drop policy if exists "Public can read published articles" on public.articles;
create policy "Public can read published articles" on public.articles for select to anon, authenticated using (status = 'published');
-- No public insert, update or delete policies. Only the private automation secret can publish.
